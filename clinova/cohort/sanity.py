"""Reproducible plausibility report; never calibrates distributions to a protocol."""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from time import perf_counter

import numpy as np

from clinova.cohort.generate import cohort_frame, generate_cohort
from clinova.cohort.traits import load_assumptions
from clinova.common.fixtures import load_fixture
from clinova.contracts import ParsedProtocol, Setting
from clinova.simulate.diversity import diversity_index
from clinova.simulate.screen import screen


def measure(n: int = 10000, seed: int = 42) -> dict:
    protocol = load_fixture("parsed_protocol.json", ParsedProtocol)
    people = generate_cohort(n, seed, protocol.setting)
    frame = cohort_frame(people)
    eligible, funnel = screen(protocol.rules, frame, trial_id=protocol.trial_id)
    parsed_rules = [r for r in protocol.rules if r.parse_status == "ok"]
    rules25 = [parsed_rules[i % len(parsed_rules)].model_copy(update={"rule_id": f"B{i}"}) for i in range(25)]
    screen(rules25, frame)
    timings = []
    for _ in range(9):
        start = perf_counter()
        screen(rules25, frame)
        timings.append((perf_counter() - start) * 1000)
    seed_shares = []
    for s in (1, 2, 3):
        other = cohort_frame(generate_cohort(n, s, protocol.setting))
        seed_shares.append(screen(protocol.rules, other)[1].eligible_frac)
    return {
        "n": n, "seed": seed, "setting": str(Setting(protocol.setting)),
        "source_counts": dict(Counter(p.source for p in people)),
        "eligible_n": funnel.n_eligible, "eligible_fraction": funnel.eligible_frac,
        "seed_1_2_3_fractions": seed_shares,
        "skipped_rules": funnel.skipped_rules,
        "diversity_index": diversity_index(frame[eligible]),
        "benchmark_25_rules_ms_median": float(np.median(timings)),
        "benchmark_25_rules_ms_max": max(timings),
        "median_age": float(frame.age.median()),
        "male_fraction": float((frame.sex == "male").mean()),
        "ecog_ge2_fraction": float((frame.ecog >= 2).mean()),
        "crcl_lt60_fraction": float((frame.crcl_ml_min < 60).mean()),
        "crcl_median": float(frame.crcl_ml_min.median()),
        "egfr_positive_fraction": float((frame.egfr_status == "positive").mean()),
        "top_marginal": [{"rule_id": r.rule_id, "excluded_n": r.excluded_n, "excluded_only_n": r.excluded_only_n} for r in funnel.marginal[:5]],
    }


def report(result: dict) -> str:
    sanity = load_assumptions()["eligibility_sanity_check"]
    restrictive = sanity["restrictive_phase3_modern"]
    academic = sanity["academic_single_center_first_line"]
    band = sanity["recommended_band_for_simulator_output"]
    fraction = result["eligible_fraction"]
    position = "below" if fraction < band["low"] else "above" if fraction > band["high"] else "within"
    return f'''# T13 cohort plausibility check

Generated by `python -m clinova.cohort.sanity --out docs/cohort_sanity.md`.
This is a synthetic protocol applied to a synthetic cohort. These are simulator
outputs, not validation on real patients and not the hand-written golden fixture.
No distribution was tuned to these eligibility fractions or to outcome labels.

The fixture's second-line protocol screened {result["n"]:,} personas at seed
{result["seed"]}; {result["eligible_n"]:,} passed ({result["eligible_fraction"]:.2%}).
Sources were `{result["source_counts"]}`. Rules skipped: `{result["skipped_rules"]}`.
Seeds 1, 2, 3 yielded {', '.join(f'{x:.2%}' for x in result["seed_1_2_3_fractions"])}.

Trial Pathfinder's published mean across ten restrictive phase III NSCLC trials
was {restrictive["fraction_eligible"]:.0%} among treated patients meeting encodable
criteria ([primary publication]({restrictive["source"][0]})). The spike's single-center
first-line estimate is {academic["fraction_eligible"]:.1%} of {academic["n"]} patients
([excerpt-only source]({academic["source"][0]})); it was not reverified here.
These are different protocols, settings and denominators. Similarity is a weak
plausibility check; it does not establish clinical validity. The YAML's 25–65% band
is itself an assumption. This run falls {position} that band; the assumed prior
immunotherapy share and ECOG cut-off are its two largest marginal exclusions.
Treatment history and lab priors are weakly supported, so this discrepancy remains
a limitation to revisit with population data. The golden fixture's separate deterministic result is
covered by the screening test, not used to tune the sampler.

The cohort median age is {result["median_age"]:g}; male share {result["male_fraction"]:.2%};
ECOG >=2 share {result["ecog_ge2_fraction"]:.2%}; CrCl <60 share
{result["crcl_lt60_fraction"]:.2%} (median {result["crcl_median"]:.2f} mL/min);
EGFR-positive share {result["egfr_positive_fraction"]:.2%}. Cockcroft–Gault is computed
from sampled age, sex, weight and creatinine, not sampled as an independent trait.
The eligible cohort's diversity index is {result["diversity_index"]:.4f}.

Screening {result["n"]:,} rows by 25 applied rules took median
{result["benchmark_25_rules_ms_median"]:.3f} ms and maximum
{result["benchmark_25_rules_ms_max"]:.3f} ms over nine warm runs. Generation is
outside this timing; timings depend on the machine. Per-rule exclusions follow:

```json
{json.dumps(result["top_marginal"], indent=2)}
```

Every spike source is preserved in `clinova/cohort/assumptions.yaml`. Additional
simulation priors live in `implementation_priors` and are explicitly marked
assumptions. The broad nonsquamous group is represented as adenocarcinoma;
subtype rules are approximate. Clinical drivers are mutually exclusive.
PD-L1 is drawn from an untested prior for all personas because ClinicalTraits
requires a numeric value; its high band is reduced for driver-positive patients.
Missing biomarker test status cannot be represented by that contract.
Stage subgroups, treatment history, lab values, frailty correlation, life
expectancy and additional conditions include unsupported priors. Hispanic is
coded as an exclusive label, scaling the race distribution among non-Hispanic
personas. This aligns with the contract but differs from the source's overlapping
ethnicity flag. Coarse age×sex resampling preserves persona narratives; source
coverage and assumed life-context fields are described in the task handoff.
'''


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, default=10000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    result = measure(args.n, args.seed)
    if args.out:
        args.out.write_text(report(result))
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
